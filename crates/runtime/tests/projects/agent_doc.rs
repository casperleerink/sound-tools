//! The generated agent doc: written, stable, and every example in it is a real record, in
//! the bytes the runtime itself would write. So the doc cannot rot.

use sound_core::{AGENT_DOC_FILE, Changes, InstanceId, Tempo, TempoMap, TimeSignature};

use crate::support::{Harness, write};

/// The fenced `json` blocks of a markdown text, as (what follows `json` on the fence, body).
fn json_examples(markdown: &str) -> Vec<(String, String)> {
    let mut examples = Vec::new();
    let mut lines = markdown.lines();
    while let Some(line) = lines.next() {
        if let Some(label) = line.strip_prefix("```json") {
            let body: Vec<&str> = lines.by_ref().take_while(|line| *line != "```").collect();
            examples.push((label.trim().to_string(), body.join("\n") + "\n"));
        }
    }
    examples
}

#[test]
fn the_agent_doc_is_written_with_every_section_and_is_stable_on_reopen() {
    let harness = Harness::new();
    let doc = std::fs::read_to_string(harness.path(AGENT_DOC_FILE)).unwrap();
    assert!(doc.starts_with("<!-- Generated by the Sound Tools runtime"));
    let headings: Vec<&str> = doc.lines().filter(|line| line.starts_with("## ")).collect();
    assert_eq!(
        headings,
        [
            "## Layout",
            "## Time",
            "## project.json",
            "## Rules",
            "## Check your work",
            "## Arrangement: tracks, clips and notes",
            "## Instrument: the synth",
            "## Tone: a sine oscillator",
            "## Inspect from a command line",
        ]
    );
    assert!(!doc.contains("{{"), "a placeholder is left");
    assert_eq!(
        std::fs::read_to_string(harness.path("CLAUDE.md")).unwrap(),
        "@AGENTS.md\n"
    );

    let modified = |harness: &Harness| {
        let metadata = std::fs::metadata(harness.path(AGENT_DOC_FILE)).unwrap();
        metadata.modified().unwrap()
    };
    let before = modified(&harness);
    std::thread::sleep(std::time::Duration::from_millis(20));
    let harness = harness.reopen();
    assert_eq!(modified(&harness), before);
    assert_eq!(
        std::fs::read_to_string(harness.path(AGENT_DOC_FILE)).unwrap(),
        doc
    );
}

#[test]
fn every_json_example_of_the_agent_doc_is_a_record_as_the_runtime_writes_it() {
    for time_signature in ["4/4", "6/8", "7/4"] {
        // The doc of a project in this time signature.
        let mut harness = Harness::new();
        let signature: TimeSignature = time_signature.parse().unwrap();
        let mut changes = Changes::new();
        changes.set_tempo_map(TempoMap::constant(signature, Tempo::default()));
        harness
            .project
            .commit("Set time signature", changes)
            .unwrap();
        harness.project.poll().unwrap();
        let doc = std::fs::read_to_string(harness.path(AGENT_DOC_FILE)).unwrap();
        let examples = json_examples(&doc);
        assert_eq!(examples.len(), 6, "{time_signature}");

        // Its examples, written into an empty folder, are a project that loads whole.
        let folder = tempfile::tempdir().unwrap();
        for (path, body) in &examples {
            assert!(
                !path.is_empty(),
                "an example does not name its file: {body}"
            );
            write(folder.path(), path, body);
        }
        let mut copy = Harness::open(folder);
        assert_eq!(copy.project.problems(), [], "{time_signature}");
        let instances: Vec<String> = copy
            .project
            .instances()
            .map(|(id, _)| id.to_string())
            .collect();
        assert_eq!(
            instances,
            [
                "arrangement",
                "arrangement/piano",
                "arrangement/piano/chords-bars-5-8",
                "arrangement/piano/instrument",
                "drone",
            ]
        );

        // The runtime writes every file again: delete all, undo, and a tempo edit with its
        // undo. The bytes are those of the examples, so an agent that copies their layout
        // makes no whitespace diff.
        let mut changes = Changes::new();
        changes.delete(&InstanceId::new("arrangement").unwrap());
        changes.delete(&InstanceId::new("drone").unwrap());
        changes.set_tempo_map(TempoMap::constant(
            signature,
            Tempo::from_bpm(90.0).unwrap(),
        ));
        copy.project.commit("Delete all", changes).unwrap();
        assert!(
            !copy
                .path("state/arrangement")
                .join("instance.json")
                .exists()
        );
        copy.project.undo().unwrap();
        for (path, body) in &examples {
            let written = std::fs::read_to_string(copy.path(path)).unwrap();
            assert_eq!(&written, body, "{path} in {time_signature}");
        }
    }
}
